# ── 合成书名的作者池 ──────────────────────────────────────────────────
# ⚠️ 这里**故意不用真实作者名**。
#
# 最初的写法是"从该分类的真实书目里随机借一个作者名",结果生成了
#   《奥斯曼史》——修昔底德      (修昔底德写的是伯罗奔尼撒战争史)
#   《私域运营方法论》——马尔科姆·格拉德威尔  (跟格拉德威尔毫无关系)
# 名字挂在一个著名的真实人物身上、内容却跟他无关,是**错误归属**。
# 测试数据也不该这么假 —— 演示时被一眼看出来就很难看。
#
# 所以合成条目统一用普通中文姓名,读起来自然,又不会冒充任何真人作品。
