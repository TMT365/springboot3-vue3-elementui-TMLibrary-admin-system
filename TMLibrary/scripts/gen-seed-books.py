def isbn13_check_digit(twelve: str) -> str:
    """ISBN-13 校验位:奇数位×1 + 偶数位×3,和 mod 10,10 减余数再 mod 10。"""
    total = sum(int(d) * (1 if i % 2 == 0 else 3) for i, d in enumerate(twelve))
    return str((10 - total % 10) % 10)


def make_isbn(seq: int) -> str:
    """978 + 9 位序号 = 12 位,第 13 位是校验位。"""
    twelve = '978' + f'{seq:09d}'
    return twelve + isbn13_check_digit(twelve)


def random_date() -> str:
    start = date(1995, 1, 1).toordinal()
    end = date(2024, 12, 31).toordinal()
    return date.fromordinal(random.randint(start, end)).isoformat()


def esc(s: str) -> str:
    """SQL 单引号转义(string 里的 ' 变成 '')。"""
    return s.replace("'", "''")


def main() -> None:
    used = set()      # 已用过的**书名**
    # ⚠️ 去重键是书名本身,不是 (书名, 作者)。
    # 上一版用 (title, author) 去重,结果同一本书名配不同作者就算"新书"
    # —— 1000 本里只有 754 个不重复书名,《荀子导读》出现了 7 次。
    # 图书馆系统里同名书应该是同一本书(多副本走库存),不该是 7 条记录。
    rows = []         # (id, title, author, isbn, price, published_date, stock, category_id)

    # 先按分类均分 1000 本:26 类,每类 38 本,余 12 本摊给前 12 类
    per = TOTAL // len(LEAF_CATEGORIES)          # 38
    remainder = TOTAL - per * len(LEAF_CATEGORIES)  # 12

    book_id = START_ID
    for idx, cat in enumerate(LEAF_CATEGORIES):
        count = per + (1 if idx < remainder else 0)
        real = REAL_BOOKS.get(cat, [])
        fb_titles, fb_suffix = FALLBACK.get(cat, (['无名'], ['之书']))
        pmin, pmax = PRICE[cat]

        for n in range(count):
            # ── 选书名:优先真实书名(连同它的真实作者),用完转合成条目 ──
            if n < len(real) and real[n][0] not in used and real[n][0] not in DEMO_TITLES:
                title, author = real[n]
            else:
                # 合成条目:书名从分类词库组合,**作者用普通姓名池**
                # (不用真实作者 —— 理由见 SYNTH_AUTHORS 上方注释)
                for attempt in range(400):
                    t = f'{random.choice(fb_titles)}{random.choice(fb_suffix)}'
                    a = random.choice(SYNTH_AUTHORS)
                    if t not in used and t not in DEMO_TITLES:
                        title, author = t, a
                        break
                else:
                    # 极端兜底:加版本后缀保证唯一
                    title = f'{random.choice(fb_titles)}{random.choice(fb_suffix)}'
                    author = random.choice(SYNTH_AUTHORS)
                    for v in VARIANTS:
                        if f'{title} {v}' not in used:
                            title = f'{title} {v}'
                            break
            used.add(title)

            rows.append((
                book_id,
                title,
                author,
                make_isbn(book_id - START_ID + 1),
                round(random.uniform(pmin, pmax), 2),
                random_date(),
                random.randint(5, 150),
                cat,
            ))
            book_id += 1

    # ── 写文件 ────────────────────────────────────────────────────────
    out = Path(__file__).resolve().parent / 'seed-1000-books.sql'
    lines = []
    lines.append('-- ' + '=' * 75)
    lines.append('-- TMLibrary 测试书库种子数据 —— 1000 本')
    lines.append('--')
    lines.append('-- 生成方式:scripts/gen-seed-books.py(固定随机种子,每次生成结果一致)')
    lines.append(f'-- id 范围 : {START_ID} ~ {book_id - 1}(连续,无跳号)')
    lines.append('--           库里现有 books.id = 3~14,所以从 15 开始')
    lines.append('--')
    lines.append('-- 用途:仪表盘压测 / 缓存预热 / 搜索候选词测试 / 分类树计数验证')
    lines.append('-- ⚠️ 这是测试数据,不要在生产环境执行')
    lines.append('--')
    lines.append('-- 用法:')
    lines.append('--   mysql -uroot -p tmlibrary < scripts/seed-1000-books.sql')
    lines.append('--')
    lines.append('-- 字段:')
    lines.append('--   id            : 连续自增(15 起);文件结尾会把 AUTO_INCREMENT 设到 1015')
    lines.append('--   title/author  : 按分类取真实书名,用完转该分类专属词库组合')
    lines.append('--   isbn          : 13 位,末位是真正的 ISBN-13 校验位')
    lines.append(f'--   price         : 按分类浮动(技术/艺术贵,绘本/教辅便宜)')
    lines.append('--   published_date: 1995-2024 均匀分布')
    lines.append('--   stock_quantity: 5~150 随机')
    lines.append(f'--   category_id   : {len(LEAF_CATEGORIES)} 个真实子类均分(每类 {per}~{per + 1} 本)')
    lines.append('--   created_time / updated_time: 不写,用表默认值 CURRENT_TIMESTAMP')
    lines.append('-- ' + '=' * 75)
    lines.append('')
    lines.append('USE `tmlibrary`;')
    lines.append('')
    lines.append('-- 幂等:先清掉本次要占用的 id 区间,重复执行不会主键冲突。')
    lines.append(f'-- 只动 id >= {START_ID} 的行,库里现有 3~14 不受影响。')
    lines.append(f'DELETE FROM `books` WHERE `id` BETWEEN {START_ID} AND {book_id - 1};')
    lines.append('')
    lines.append('INSERT INTO `books`')
    lines.append('    (`id`, `title`, `author`, `isbn`, `price`, `published_date`, `stock_quantity`, `category_id`)')
    lines.append('VALUES')

    for i, (bid, title, author, isbn, price, pdate, stock, cat) in enumerate(rows):
        comma = ',' if i < len(rows) - 1 else ';'
        lines.append(
            f"  ({bid}, '{esc(title)}', '{esc(author)}', '{isbn}', {price:.2f}, "
            f"'{pdate}', {stock}, {cat}){comma}"
        )

    lines.append('')
    lines.append('-- ---------------------------------------------------------------------------')
    lines.append('-- 把自增起点推到种子数据之后 —— 否则后续在后台新增图书会从 15 开始,')
    lines.append('-- 和这批种子数据主键冲突。')
    lines.append('-- ---------------------------------------------------------------------------')
    lines.append(f'ALTER TABLE `books` AUTO_INCREMENT = {book_id};')
    lines.append('')
    lines.append('-- ---------------------------------------------------------------------------')
    lines.append('-- 回填分类计数 —— book_count 是"直接挂载在本分类下的图书数",')
    lines.append('-- 后台新建/删除图书时由 CategoryServiceImpl 维护,批量导入后要手动重算一次。')
    lines.append('-- ---------------------------------------------------------------------------')
    lines.append('UPDATE `book_categories` c')
    lines.append('SET c.`book_count` = (')
    lines.append('    SELECT COUNT(*) FROM `books` b WHERE b.`category_id` = c.`id`')
    lines.append(');')
    lines.append('')

    out.write_text('\n'.join(lines), encoding='utf-8')

    # ── 自检 ──────────────────────────────────────────────────────────
    ids = [r[0] for r in rows]
    isbns = [r[3] for r in rows]
    titles = [r[1] for r in rows]
    assert ids == list(range(START_ID, START_ID + TOTAL)), 'id 不连续'
    assert len(set(isbns)) == TOTAL, f'ISBN 有重复:{TOTAL - len(set(isbns))} 个'
    assert len(set(titles)) == TOTAL, f'书名有重复:{TOTAL - len(set(titles))} 个'
    for isbn in isbns:
        assert isbn13_check_digit(isbn[:12]) == isbn[12], f'ISBN 校验位错:{isbn}'

    print(f'✓ 生成 {out}')
    print(f'  {len(lines)} 行 / {out.stat().st_size / 1024:.1f} KB')
    print(f'  id 区间   : {ids[0]} ~ {ids[-1]}(连续 {len(ids)} 个)')
    print(f'  ISBN 唯一 : {len(set(isbns))}')
    print(f'  书名唯一  : {len(set(titles))}')
    print(f'  校验位    : 全部通过')
    from collections import Counter
    cc = Counter(r[7] for r in rows)
    print(f'  分类分布  : {len(cc)} 个子类,每类 {min(cc.values())}~{max(cc.values())} 本')


if __name__ == '__main__':
    main()
